"""Сведения о семье и инструкции для Claude (системный промпт).

Хотите поменять характер бота — правьте текст здесь.
Когда дети подрастут, обновите возраст в FAMILY.
"""

from __future__ import annotations

from datetime import date

CITY = "Краснодар"

FAMILY = (
    "Сергей — папа",
    "Вика — мама, жена Сергея",
    "Никита — сын, 8 лет",
    "Катя — дочь, 3 года",
)

_WEEKDAYS = (
    "понедельник",
    "вторник",
    "среда",
    "четверг",
    "пятница",
    "суббота",
    "воскресенье",
)

_MONTHS = (
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
)


def format_date(day: date) -> str:
    """4 ноября 2026, среда."""
    return f"{day.day} {_MONTHS[day.month - 1]} {day.year}, {_WEEKDAYS[day.weekday()]}"


def season(day: date) -> str:
    if day.month in (12, 1, 2):
        return "зима"
    if day.month in (3, 4, 5):
        return "весна"
    if day.month in (6, 7, 8):
        return "лето"
    return "осень"


def build_system_prompt(today: date) -> str:
    family_lines = "\n".join(f"• {person}" for person in FAMILY)
    return f"""Ты — «Семейный помощник», бот в Telegram для одной семьи из города {CITY}.

Семья:
{family_lines}

Сегодня {format_date(today)}. Время года: {season(today)}.

Как отвечать:
• По-русски, простым языком, коротко и по делу. Обращайся на «вы».
• Где уместно, учитывай возраст детей и то, что семья живёт в Краснодаре (климат, город, окрестности).
• Telegram показывает ответ как обычный текст: не используй Markdown (никаких **, #, таблиц). Для списков — «•» или цифры, можно немного эмодзи.
• Если не уверен в факте (цены, расписание, часы работы, адреса, погода) — так и скажи и посоветуй проверить на официальном сайте. Ничего не выдумывай.
• На вопросы о здоровье, праве и деньгах давай общую информацию и советуй обратиться к специалисту."""


def build_weekend_request(today: date) -> str:
    return f"""Предложи 5 идей, как провести ближайшие выходные всей семьёй.
Учитывай: мы в Краснодаре, сейчас {season(today)}, детям 8 и 3 года — идея должна подходить обоим.
Сделай разнообразно: что-то дома, что-то на улице в городе и одну поездку недалеко (до 1,5 часа на машине).
Для каждой идеи: название, 1–2 предложения, примерный бюджет словами (бесплатно / недорого / подороже) и что взять с собой.
Точные цены и часы работы не придумывай — напиши, что их лучше уточнить."""
